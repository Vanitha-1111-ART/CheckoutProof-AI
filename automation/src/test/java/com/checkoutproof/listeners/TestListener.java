package com.checkoutproof.listeners;

import com.checkoutproof.utils.DriverManager;
import com.checkoutproof.utils.ScreenshotUtil;
import org.openqa.selenium.WebDriver;
import org.testng.ITestContext;
import org.testng.ITestListener;
import org.testng.ITestResult;

import java.net.URI;
import java.net.http.HttpClient;
import java.net.http.HttpRequest;
import java.net.http.HttpResponse;
import java.time.Duration;

/**
 * TestListener intercepts TestNG execution events.
 * Automatically takes a failure screenshot and optionally forwards failure context
 * to the CheckoutProof AI triage microservice at http://127.0.0.1:8000/analyze.
 */
public class TestListener implements ITestListener {

    private static final String AI_SERVICE_URL = "http://127.0.0.1:8000/analyze";
    private final HttpClient httpClient = HttpClient.newBuilder()
            .connectTimeout(Duration.ofSeconds(2))
            .build();

    @Override
    public void onTestStart(ITestResult result) {
        System.out.println("\n[STARTING TEST] >>> " + result.getMethod().getMethodName());
    }

    @Override
    public void onTestSuccess(ITestResult result) {
        System.out.println("[TEST PASSED] ✔ " + result.getMethod().getMethodName());
    }

    @Override
    public void onTestFailure(ITestResult result) {
        String testName = result.getMethod().getMethodName();
        String errorMessage = result.getThrowable() != null ? result.getThrowable().getMessage() : "Unknown assertion failure";
        System.err.println("[TEST FAILED] ✖ " + testName + " - Error: " + errorMessage);

        // 1. Capture failure screenshot
        WebDriver driver = DriverManager.getDriver();
        String screenshotPath = null;
        if (driver != null) {
            screenshotPath = ScreenshotUtil.captureScreenshot(driver, testName);
            System.out.println("[TestListener] Screenshot stored for failure analysis: " + screenshotPath);
        }

        // 2. Dispatch to AI Failure Analysis Service (non-blocking, graceful fallback)
        dispatchToAiService(testName, errorMessage, result.getThrowable(), screenshotPath);
    }

    private void dispatchToAiService(String testName, String errorMessage, Throwable throwable, String screenshotPath) {
        try {
            StringBuilder stackTraceBuilder = new StringBuilder();
            if (throwable != null) {
                for (StackTraceElement elem : throwable.getStackTrace()) {
                    stackTraceBuilder.append(elem.toString()).append("\n");
                    if (stackTraceBuilder.length() > 1000) break;
                }
            }

            // Construct sanitized JSON payload manually to avoid heavy external dependencies
            String jsonPayload = String.format(
                    "{\"test_name\":\"%s\",\"error_message\":\"%s\",\"stack_trace\":\"%s\",\"screenshot_path\":\"%s\",\"source\":\"selenium_listener\",\"test_status\":\"ASSERTION_FAILURE\"}",
                    escapeJson(testName),
                    escapeJson(errorMessage),
                    escapeJson(stackTraceBuilder.toString()),
                    escapeJson(screenshotPath != null ? screenshotPath.replace("\\", "/") : "")
            );

            HttpRequest request = HttpRequest.newBuilder()
                    .uri(URI.create(AI_SERVICE_URL))
                    .header("Content-Type", "application/json")
                    .timeout(Duration.ofSeconds(4))
                    .POST(HttpRequest.BodyPublishers.ofString(jsonPayload))
                    .build();

            HttpResponse<String> response = httpClient.send(request, HttpResponse.BodyHandlers.ofString());
            if (response.statusCode() == 200) {
                System.out.println("[CheckoutProof AI] Failure triage report generated by AI Service.");
            } else {
                System.out.println("[CheckoutProof AI] Service responded with status " + response.statusCode());
            }
        } catch (Exception e) {
            // Graceful degradation: never interrupt or fail test execution if AI service is offline
            System.out.println("[TestListener] AI Service offline or unreachable; test reports preserved without interruption.");
        }
    }

    private String escapeJson(String input) {
        if (input == null) return "";
        return input.replace("\\", "\\\\")
                    .replace("\"", "\\\"")
                    .replace("\b", "\\b")
                    .replace("\f", "\\f")
                    .replace("\n", "\\n")
                    .replace("\r", "\\r")
                    .replace("\t", "\\t");
    }

    @Override
    public void onTestSkipped(ITestResult result) {
        System.out.println("[TEST SKIPPED] ⚠ " + result.getMethod().getMethodName());
    }

    @Override
    public void onStart(ITestContext context) {
        System.out.println("=== Test Suite Execution Started: " + context.getName() + " ===");
    }

    @Override
    public void onFinish(ITestContext context) {
        System.out.println("=== Test Suite Execution Finished: " + context.getName() + " ===");
    }
}
