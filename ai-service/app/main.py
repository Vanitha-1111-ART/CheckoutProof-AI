@app.post("/analyze", response_model=AiAnalysisResult, tags=["Analysis"])
def analyze_failure(payload: TestFailureInput):
    """
    Analyzes an automated test failure or manual test payload.
    Includes execution_id, timestamp, source, and authoritative test_status metadata.
    """
    if not payload.test_name or not payload.error_message:
        raise HTTPException(status_code=400, detail="test_name and error_message are required fields.")

    result = analyze_with_gemini(payload)

    # Persist report to reports/ai-analysis/
    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    safe_name = "".join(c for c in payload.test_name if c.isalnum() or c in ("-", "_"))
    prefix = "selenium" if result.source == "selenium_listener" else "manual"
    report_file = REPORTS_DIR / f"{prefix}_{safe_name}_{timestamp}.json"

    try:
        with open(report_file, "w", encoding="utf-8") as f:
            json.dump(result.model_dump(), f, indent=2)
    except Exception as e:
        print(f"[Warning] Failed to write report file: {e}")

    return result


@app.post("/reports/clear-demo", response_model=ClearDemoResponse, tags=["Report Management"])
def clear_demo_reports():
    """
    Clears manual, demo, and sample API reports while strictly preserving
    all actual Selenium automation failure reports.
    """
    cleared = 0
    preserved = 0

    if REPORTS_DIR.exists():
        for p in list(REPORTS_DIR.glob("*.json")):
            try:
                with open(p, "r", encoding="utf-8") as f:
                    data = json.load(f)

                source = data.get("source", "manual_api")
                test_name = data.get("test_name", "")

                # Keep real selenium automation reports
                if source == "selenium_listener" or "testBlankCustomerNameValidation_20261123_042125407" in str(data.get("suggested_bug_report", "")):
                    preserved += 1
                    continue

                # Delete demo/manual/swagger test reports
                if source in ("manual_api", "demo_sample") or test_name in ("string", "sample") or "string" in p.name:
                    p.unlink(missing_ok=True)
                    cleared += 1
                else:
                    preserved += 1
            except Exception as e:
                print(f"[Warning] Error processing file {p}: {e}")

    return ClearDemoResponse(
        status="SUCCESS",
        cleared_count=cleared,
        preserved_selenium_count=preserved,
        message=f"Cleaned {cleared} demo/sample reports. Preserved {preserved} Selenium reports."
    )


